#!/usr/bin/env python3
"""Sync the generated paper tables into the alinker-paper repo, and guard against drift.

Single source of truth for the engine -> paper bridge (replaces the hand ``cp`` blocks in
HOWTO-REGENERATE-RQ.md). The RQ table set is derived from ``csv_to_tex.SPECS``, so it tracks
table adds/removes automatically: each spec's rendered ``reports/tex/<out>.tex`` is copied into
the paper, together with its ``reports/tex_src/<csv>`` companion (renamed to ``<out-stem>.csv``).
The body tables land in ``<paper>/table``; every other table in ``<paper>/appendix``.
``gold_concentration.{tex,csv}`` (the OUT-02 inequality artifacts) is synced too.
The RQ1 cost-table include and its existing explanation belong in the RQ1 subsection;
the RQ sync places that block there and ``--check`` detects any drift.

    python3 mini-src/sync_paper.py             # copy generated files into the paper
    python3 mini-src/sync_paper.py --check      # byte-diff only; exit 1 on drift (CI guard)
    python3 mini-src/sync_paper.py --only rq    # restrict to the RQ tables (skip gold)
    PAPER_DIR=/path/to/alinker-paper python3 mini-src/sync_paper.py
    python3 mini-src/sync_paper.py /path/to/alinker-paper

Run the generators first (``rq_tables.py`` + ``csv_to_tex.py``); ``--check`` compares the
already-generated files and does not rebuild the RQ tables. Exit 0 = done / in sync;
1 = drift (``--check``); 2 = paper dir not found.
"""
from __future__ import annotations

import argparse
import difflib
import shutil
import sys
from pathlib import Path

import csv_to_tex as c2t

HERE = Path(__file__).resolve().parent          # .../transarc-emp/mini-src
EVAL = HERE.parent                              # .../transarc-emp

# The body tables; everything else generated by csv_to_tex goes to the appendix.
BODY = {"rq1-results.tex", "rq2-results.tex", "rq3-confusion.tex", "rq4-results.tex",
        "rq4-floor.tex", "inference-cost.tex"}
COST_INCLUDE = r"\input{table/inference-cost}"
COST_EXPLANATION = r"\autoref{tab:inference-cost}"
RQ1_HEADING = r"\subsection{Answer to RQ1}"
RQ2_HEADING = r"\subsection{Answer to RQ2}"
SUMMARY_HEADING = r"\subsection{Summary}"


def rq_pairs():
    """(generated_path, paper_subdir, paper_filename) for every RQ .tex + its companion .csv."""
    for spec in c2t.SPECS:
        out = spec["out"]                                       # e.g. big-table-perproject.tex
        subdir = "table" if out in BODY else "appendix"
        yield c2t.TEX_OUT / out, subdir, out                    # rendered table
        yield c2t.TEX_SRC / spec["csv"], subdir, Path(out).stem + ".csv"  # reviewable companion


def gold_pairs(regenerate=True):
    """(generated_path, 'table', paper_filename) for the OUT-02 gold_concentration pair.

    Imported lazily so RQ-only syncs do not depend on the inequality engine / benchmark."""
    sys.path.insert(0, str(EVAL / "mini-inequality"))
    import motivation as mot
    if regenerate:
        mot.write_out02_concentration()
    yield mot.REPORTS / "out02_concentration.tex", "table", "gold_concentration.tex"
    yield mot.REPORTS / "out02_concentration.csv", "table", "gold_concentration.csv"


def plan(only, regenerate_gold):
    items = []
    if only in ("all", "rq"):
        items += list(rq_pairs())
    if only in ("all", "gold"):
        items += list(gold_pairs(regenerate=regenerate_gold))
    return items


def locate_paper_dir(arg=None):
    candidates = [
        arg,
        # sibling repo layout: .../transarc-emp -> .../alinker-paper
        EVAL.parent / "alinker-paper",
        # mono symlink lens, if present
        EVAL.parent / "mono" / "working",
    ]
    for c in candidates:
        if c and (Path(c) / "table").is_dir() and (Path(c) / "appendix").is_dir():
            return Path(c)
    return None


def sync_rq1_cost_placement(paper, check):
    """Move the existing cost-table block into RQ1, preserving its authored text."""
    section = paper / "sections" / "results.tex"
    if not section.is_file():
        raise ValueError(f"missing Results section: {section}")
    old = section.read_text(encoding="utf-8")
    if old.count(COST_INCLUDE) != 1 or old.count(COST_EXPLANATION) != 1:
        raise ValueError(f"expected one cost-table include and explanation in {section}")
    rq1 = old.index(RQ1_HEADING)
    rq2 = old.index(RQ2_HEADING)
    include_start = old.index(COST_INCLUDE)
    explanation_start = old.index(COST_EXPLANATION)
    if rq1 < include_start < explanation_start < rq2:
        return 0
    summary = old.index(SUMMARY_HEADING)
    if not (rq1 < include_start < rq2 or summary < include_start):
        raise ValueError(f"cost-table include is outside RQ1 and Summary in {section}")
    if not (rq1 < explanation_start < rq2 or summary < explanation_start):
        raise ValueError(f"cost-table explanation is outside RQ1 and Summary in {section}")

    blocks = []
    for start in (include_start, explanation_start):
        end = old.find("\n\n", start)
        if end < 0:
            raise ValueError(f"cost-table block has no terminating blank line in {section}")
        blocks.append((start, end + 2, old[start:end + 2]))
    if blocks[0][1] > blocks[1][0] and blocks[1][1] > blocks[0][0]:
        raise ValueError(f"cost-table include overlaps its explanation in {section}")
    block = blocks[0][2] + blocks[1][2]
    without_block = old
    for start, end, _ in sorted(blocks, reverse=True):
        without_block = without_block[:start] + without_block[end:]
    insertion = without_block.index(RQ2_HEADING)
    new = without_block[:insertion] + block + without_block[insertion:]
    if check:
        print(f"\nDRIFT: {section} places the cost table outside RQ1")
        sys.stdout.writelines(difflib.unified_diff(
            old.splitlines(keepends=True), new.splitlines(keepends=True),
            fromfile=str(section), tofile=f"generated placement in {section}"))
        return 1
    section.write_text(new, encoding="utf-8")
    print(f"placed cost table and explanation in RQ1: {section}")
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(description="Sync / check the paper tables.")
    ap.add_argument("paper_dir", nargs="?", help="alinker-paper root (else env PAPER_DIR / autodetect)")
    ap.add_argument("--check", action="store_true", help="diff only; exit 1 on drift")
    ap.add_argument("--only", choices=("all", "rq", "gold"), default="all")
    args = ap.parse_args(argv)

    import os
    paper = locate_paper_dir(args.paper_dir or os.environ.get("PAPER_DIR"))
    if paper is None:
        print("ERROR: could not locate the alinker-paper root (needs table/ + appendix/).")
        print("Pass it as an argument or set PAPER_DIR=...")
        return 2

    items = plan(args.only, regenerate_gold=True)
    drift = changed = dropped = 0
    for gen, subdir, name in items:
        dest = paper / subdir / name
        if not gen.is_file():
            # A table this arm does not have (the one-call floor on an arm with no floor
            # sweep) is DROPPED, not drift: leaving the previous arm's copy in the paper
            # is how a stale number survives a promotion. A table the generators should
            # have written and did not is still an error there, where it is diagnosable.
            print(f"absent for this arm: {gen.name}"
                  + (f"  (removing {dest})" if dest.is_file() else ""))
            if dest.is_file() and not args.check:
                dest.unlink()
            dropped += 1
            continue
        if args.check:
            old = dest.read_text() if dest.is_file() else ""
            new = gen.read_text()
            if old == new:
                continue
            drift += 1
            print(f"\nDRIFT: {dest} differs from {gen}")
            sys.stdout.writelines(difflib.unified_diff(
                old.splitlines(keepends=True), new.splitlines(keepends=True),
                fromfile=str(dest), tofile=str(gen)))
        else:
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(gen, dest)
            changed += 1

    if args.only in ("all", "rq"):
        try:
            drift += sync_rq1_cost_placement(paper, args.check)
        except ValueError as error:
            print(f"ERROR: {error}")
            return 2

    tail = f" ({dropped} absent for this arm)" if dropped else ""
    if args.check:
        print(f"\n{'DRIFT' if drift else 'IN SYNC'}: {drift} file(s) out of date.{tail}"
              if drift else
              f"IN SYNC: all {len(items) - dropped} paper file(s) match the generated "
              f"output.{tail}")
        return 1 if drift else 0
    print(f"synced {changed} file(s) into {paper}{tail}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
